/**
 * Keep the terminal's chrome glyphs (toolbar, rails, menus) aligned with the
 * installed draw tier without loading that tier when the toolbar renders.
 * The sibling of generate-drawing-tools.mjs: that one owns the tool menu's
 * names and glyphs, this one owns the buttons around the chart.
 * Run from frontend: node scripts/generate-chrome-icons.mjs [--check]
 */
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import {
  CHROME_ICON_ACCENTS,
  CHROME_ICON_FILLED,
  CHROME_ICON_SIZE,
  CHROME_ICON_STROKE,
  CHROME_ICONS,
  DRAWING_TOOL_ACCENTS,
  DRAWING_TOOL_ICONS,
  ICON_SIZE,
  ICON_STROKE,
} from 'openalgo-charts/draw'

// Rail glyphs that are not tools, so the drawing metadata does not carry them.
const RAIL_GLYPHS = ['cursor', 'magnet']

const output = new URL('../src/lib/trading/chromeIcons.ts', import.meta.url)
const sorted = (record) => Object.fromEntries(Object.keys(record).sort().map((id) => [id, record[id]]))
for (const id of RAIL_GLYPHS) assert(DRAWING_TOOL_ICONS[id], `Missing rail glyph ${id}`)
const rail = Object.fromEntries(RAIL_GLYPHS.map((id) => [id, DRAWING_TOOL_ICONS[id]]))

const content = `// Generated by frontend/scripts/generate-chrome-icons.mjs from the pinned package.
// Static so the toolbar and the rails draw the engine's glyphs without loading the draw tier.

/** CSS pixel size the chrome glyphs are drawn for, on a 16 unit grid. */
export const CHROME_ICON_SIZE = ${CHROME_ICON_SIZE}
/** Chrome stroke in viewBox units: about 1.3px at CHROME_ICON_SIZE. */
export const CHROME_ICON_STROKE = ${CHROME_ICON_STROKE}
/** CSS pixel size the tool glyphs are drawn for, on a 24 unit grid. */
export const TOOL_ICON_SIZE = ${ICON_SIZE}
/** Tool stroke in viewBox units: about 1.3px at TOOL_ICON_SIZE. */
export const TOOL_ICON_STROKE = ${ICON_STROKE}

/** Path data for every chrome glyph, by id. */
export const CHROME_ICON_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(sorted(CHROME_ICONS), null, 2)}

/** The solid marks painted over a chrome glyph's own outline. */
export const CHROME_ICON_ACCENT_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(sorted(CHROME_ICON_ACCENTS), null, 2)}

/** Chrome glyphs painted solid as well as stroked. */
export const CHROME_ICON_FILLED_IDS: ReadonlySet<string> = new Set(${JSON.stringify([...CHROME_ICON_FILLED].sort())})

/** Rail glyphs on the tool grid that are not themselves tools. */
export const RAIL_TOOL_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(rail, null, 2)}

/** The solid marks painted over a tool glyph's own outline (anchor dots, heads). */
export const TOOL_ICON_ACCENT_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(sorted(DRAWING_TOOL_ACCENTS), null, 2)}
`
if (process.argv.includes('--check')) {
  assert.equal(
    readFileSync(output, 'utf8').replace(/\r\n/g, '\n'),
    content,
    'Regenerate chrome icons for the pinned package'
  )
} else {
  writeFileSync(output, content)
}
