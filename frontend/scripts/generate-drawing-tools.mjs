/**
 * Keep rail labels and glyphs aligned with the installed drawing registry
 * without loading the drawing renderer when the host imports its menu.
 * Run from frontend: node scripts/generate-drawing-tools.mjs [--check]
 */
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { registeredDrawingTools, DRAWING_TOOL_ICONS, ICON_ATTRS } from 'openalgo-charts/draw'

const output = new URL('../src/lib/trading/drawingToolMetadata.ts', import.meta.url)
const metadata = Object.fromEntries(registeredDrawingTools().map((tool) => {
  assert(DRAWING_TOOL_ICONS[tool.id], `Missing glyph for ${tool.id}`)
  return [tool.id, {
    name: tool.name,
    path: DRAWING_TOOL_ICONS[tool.id],
    text: tool.settings?.textIsContent === true || tool.id === 'price-label',
    ...(tool.settings?.textIsContent || tool.id === 'price-label' ? { fields: tool.settings.fields.map(field => field.path) } : {}),
  }]
}))
const content = `// Generated by frontend/scripts/generate-drawing-tools.mjs from the pinned package.
// Metadata keeps the menu independent of the lazily loaded drawing renderer.
export const DRAW_TOOL_METADATA: Readonly<Record<string, { name: string; path: string; text: boolean; fields?: readonly string[] }>> = ${JSON.stringify(metadata, null, 2)}

export const DRAW_TOOL_ICON_ATTRS = ${JSON.stringify(ICON_ATTRS, null, 2)} as const
`
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(output, 'utf8').replace(/\r\n/g, '\n'), content, 'Regenerate drawing metadata for the pinned package')
} else {
  writeFileSync(output, content)
}
