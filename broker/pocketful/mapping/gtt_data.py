"""OpenAlgo GTT requests to Pocketful's GTT rules, and Pocketful's book back.

Pocketful docs, "Create GTT Order" and "Modify GTT Order": a rule is

    {"action_type": "single_order", "expiry_time": "YYYY-MM-DD",
     "order": {"client_id", "disclosed_quantity", "exchange",
               "instrument_token", "market_protection_percentage",
               "order_side", "order_type", "price", "product", "quantity",
               "sl_order_price", "sl_order_quantity", "sl_trigger_price",
               "trigger_price", "user_order_id"}}

and a modify adds the rule's ``id`` (and ``"device": "web"`` in the order, as
the modify example sends it). What OpenAlgo's contract asks for, and what of it
Pocketful's documentation covers:

    SINGLE      supported. trigger_price is the trigger; price the child
                order's limit.
    OCO         refused. The only action_type documented is "single_order";
                the sl_* order fields exist but the docs never show a value
                that turns them on, and a guessed two-leg rule could fire a
                stop nobody set.
    MARKET      emulated. The annexure allows only LIMIT and SL through the
                API, so a MARKET child is sent as a LIMIT protected by the
                shared MPP slabs. The protection is measured from the trigger
                price, because that is the price at which the child order is
                placed: measured from today's LTP, a SELL stop below the
                market would carry a limit above the price it fires at and
                never fill.
    expiry      required by Pocketful (a date). OpenAlgo's ``expires_at`` is
                used when sent; otherwise a derivative expires with its
                contract and anything else in one year. A modify keeps the
                expiry the rule already has.
"""

import itertools
import math
import re
import time
from datetime import datetime, timedelta

from database.token_db import get_oa_symbol, get_symbol, get_symbol_info
from utils.logging import get_logger
from utils.mpp_slab import calculate_protected_price, get_instrument_type_from_symbol

logger = get_logger(__name__)

ACTION_TYPE = "single_order"
GTT_PRODUCTS = ("CNC", "NRML", "MIS")
INDEX_EXCHANGES = ("NSE_INDEX", "BSE_INDEX")
DERIVATIVE_EXCHANGES = ("NFO", "BFO", "MCX", "CDS", "BCD")
DEFAULT_VALIDITY_DAYS = 365

# A GTT id Pocketful issues is a UUID. Anything else is refused before it is
# put into a request path.
_TRIGGER_ID = re.compile(r"^[A-Za-z0-9-]{1,64}$")

# "Error from backend: (500)-event id not found" -> "event id not found".
_BACKEND_PREFIX = re.compile(r"^\s*error from backend:\s*(\(\s*\d+\s*\)\s*-?\s*)?", re.I)

# user_order_id: "The unique order ID generated by the user" (an integer).
# Seeded from the clock so a restart does not reuse the last run's numbers,
# and kept below 2**31.
_user_order_ids = itertools.count(int(time.time() * 1000) % 1_000_000_000)

OCO_REFUSAL = (
    "Pocketful's GTT takes one trigger only, so an OCO (stop loss and target "
    "together) cannot be placed. Place the stop loss and the target as two "
    "SINGLE GTTs; Pocketful will not cancel one when the other fires."
)


class GttRefused(Exception):
    """A request refused before anything is sent; the message is for the trader."""

    def __init__(self, message, status_code=400):
        super().__init__(message)
        self.status_code = status_code


def broker_reason(message):
    """Pocketful's own message without its backend code prefix, or ""."""
    text = _BACKEND_PREFIX.sub("", str(message or "")).strip()
    return text[:1].upper() + text[1:] if text else ""


def valid_trigger_id(trigger_id):
    return bool(trigger_id) and bool(_TRIGGER_ID.match(str(trigger_id)))


def next_user_order_id():
    return next(_user_order_ids) % 2_000_000_000


def _float(value):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0.0
    return number if math.isfinite(number) else 0.0


def trigger_price(data):
    """The SINGLE trigger: the schema's ``trigger_price``, else whichever of
    triggerprice_sl / triggerprice_tg is set (a route that bypasses the schema
    sends only those)."""
    for key in ("trigger_price", "triggerprice_sl", "triggerprice_tg"):
        value = _float(data.get(key))
        if value > 0:
            return value
    return 0.0


def _instrument(data):
    symbol = data.get("symbol")
    exchange = data.get("exchange")
    if exchange in INDEX_EXCHANGES:
        raise GttRefused("An index cannot be traded, so a GTT cannot be placed on it.")
    info = get_symbol_info(symbol, exchange) if symbol and exchange else None
    if info is None or not info.token:
        raise GttRefused(
            f"{symbol} on {exchange} is not in the Pocketful master contract. Check "
            "the symbol, or download the master contract again and retry."
        )
    return info


def _limit_price(data, info, trigger, action):
    pricetype = str(data.get("pricetype") or "LIMIT").upper()
    if pricetype == "LIMIT":
        price = _float(data.get("price"))
        if price <= 0:
            raise GttRefused("A LIMIT GTT needs a limit price above zero.")
        return price
    if pricetype != "MARKET":
        raise GttRefused("The GTT price type must be LIMIT or MARKET.")

    tick = _float(getattr(info, "tick_size", None))
    price = calculate_protected_price(
        price=trigger,
        action=action,
        symbol=data.get("symbol"),
        instrument_type=get_instrument_type_from_symbol(data.get("symbol"), data.get("exchange")),
        tick_size=tick if tick > 0 else None,
    )
    if price <= 0:
        raise GttRefused(
            "The trigger price is too low to protect a MARKET order. Send a LIMIT GTT "
            "with the price you want instead."
        )
    return price


def build_gtt_order(data, client_id):
    """(order block, SymbolData) for a SINGLE GTT. Raises GttRefused."""
    if str(data.get("trigger_type") or "SINGLE").upper() == "OCO":
        raise GttRefused(OCO_REFUSAL)

    action = str(data.get("action") or "").upper()
    if action not in ("BUY", "SELL"):
        raise GttRefused("The GTT action must be BUY or SELL.")

    product = str(data.get("product") or "").upper()
    if product not in GTT_PRODUCTS:
        raise GttRefused("The GTT product must be CNC or NRML.")

    quantity = _float(data.get("quantity"))
    if quantity <= 0 or not quantity.is_integer():
        raise GttRefused("The GTT quantity must be a whole number above zero.")

    trigger = trigger_price(data)
    if trigger <= 0:
        raise GttRefused("A GTT needs a trigger price above zero.")

    info = _instrument(data)
    price = _limit_price(data, info, trigger, action)

    order = {
        "client_id": client_id,
        "disclosed_quantity": 0,
        "exchange": info.brexchange or data.get("exchange"),
        "instrument_token": str(info.token),
        "market_protection_percentage": 0,
        "order_side": action,
        "order_type": "LIMIT",
        "price": price,
        "product": product,
        "quantity": int(quantity),
        "sl_order_price": 0,
        "sl_order_quantity": 0,
        "sl_trigger_price": 0,
        "trigger_price": trigger,
        "user_order_id": next_user_order_id(),
    }
    return order, info


def _parse_date(text):
    text = str(text or "").strip()
    for fmt in ("%Y-%m-%d", "%d-%b-%y", "%d-%b-%Y", "%d%b%y", "%d%b%Y"):
        try:
            return datetime.strptime(text, fmt).date()
        except ValueError:
            continue
    return None


def expiry_date(data, info, today):
    """The rule's expiry_time ("YYYY-MM-DD"). Raises GttRefused on a bad expires_at."""
    requested = data.get("expires_at")
    if requested:
        chosen = _parse_date(str(requested)[:10])
        if chosen is None or chosen < today:
            raise GttRefused(
                "The GTT expiry must be a date from today onward, written as YYYY-MM-DD."
            )
        return chosen.isoformat()

    if data.get("exchange") in DERIVATIVE_EXCHANGES:
        contract = _parse_date(getattr(info, "expiry", None))
        if contract is not None and contract >= today:
            return contract.isoformat()

    return (today + timedelta(days=DEFAULT_VALIDITY_DAYS)).isoformat()


def gtt_rows(payload):
    """The rules in a fetch answer's ``data`` member, as a list."""
    if isinstance(payload, list):
        return [row for row in payload if isinstance(row, dict)]
    if isinstance(payload, dict) and payload.get("id"):
        return [payload]
    return []


def row_status(row):
    order = row.get("order") if isinstance(row.get("order"), dict) else {}
    return str(order.get("status") or row.get("status") or "").strip().lower()


def _oa_symbol(order):
    exchange = order.get("exchange", "")
    brsymbol = order.get("trading_symbol", "")
    token = order.get("token") or order.get("instrument_token")
    symbol = get_oa_symbol(brsymbol, exchange) if brsymbol else None
    if not symbol and token not in (None, ""):
        symbol = get_symbol(str(token), exchange)
    return symbol or brsymbol


def map_gtt_book(rows, include_history=False):
    """Pocketful rules to OpenAlgo's GTT book rows (docs/api gttorderbook.md).

    Fields from the "Fetch GTT Order" page: the rule's id, action_type,
    created_at and expiry_time, and inside ``order`` the exchange, token,
    trading_symbol, order_side, order_type, price, prod_type, quantity,
    trigger_price, status ("Active") and updated_at. Pocketful does not report
    a last price, so it reads 0.
    """
    book = []
    for row in rows:
        status = row_status(row)
        if not include_history and status != "active":
            continue
        order = row.get("order") if isinstance(row.get("order"), dict) else {}
        action_type = str(row.get("action_type") or "")
        book.append(
            {
                "trigger_id": str(row.get("id", "")),
                "trigger_type": "single" if action_type == ACTION_TYPE else action_type,
                "status": status,
                "symbol": _oa_symbol(order),
                "exchange": order.get("exchange", ""),
                "trigger_prices": [_float(order.get("trigger_price"))],
                "last_price": 0,
                "legs": [
                    {
                        "action": str(order.get("order_side", "")).upper(),
                        "quantity": int(_float(order.get("quantity"))),
                        "price": _float(order.get("price")),
                        "pricetype": str(order.get("order_type", "")).upper(),
                        "product": str(order.get("prod_type") or order.get("product") or ""),
                    }
                ],
                "created_at": str(row.get("created_at") or ""),
                "updated_at": str(order.get("updated_at") or row.get("updated_at") or ""),
                "expires_at": str(row.get("expiry_time") or ""),
            }
        )
    return book


def today_ist():
    from zoneinfo import ZoneInfo

    return datetime.now(ZoneInfo("Asia/Kolkata")).date()
