/**
 * The benchmark every release publishes: `benchmarks/releases.json` holds one
 * entry per version from 2.5.8 on, each the render bench measured on the new
 * build and on the release before it, in one session on one machine. The
 * website's Benchmarks page quotes the file between two markers, and this
 * module renders that block, so the page cannot drift from the data (the same
 * rule scripts/check-render-bench-docs.mjs applies to the CI budgets).
 *
 * `npm run bench:release` writes the entry and the page; `node
 * scripts/check-benchmark-page.mjs` fails CI when they disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BENCH_BAR_COUNTS, BENCH_METRICS, BENCH_RENDERERS } from './render-bench-budgets.mjs';

export const DATA_FILE = fileURLToPath(new URL('../benchmarks/releases.json', import.meta.url));
export const PAGE_FILE = fileURLToPath(new URL('../website/pages/benchmarks.mdx', import.meta.url));
export const START = '{/* release-benchmarks:start (generated by npm run bench:release; check: node scripts/check-benchmark-page.mjs) */}';
export const END = '{/* release-benchmarks:end */}';

/** What each metric times, as the page's column headings say it. */
const COLUMNS = { pan: 'Pan frame p95', zoomOut: 'Full zoom-out frame p95', tick: 'Tick p95, 10 studies' };

/** @returns {{ schema: number, releases: any[] }} */
export function readReleases() {
  return JSON.parse(readFileSync(DATA_FILE, 'utf8'));
}

/** Compare two x.y.z versions. */
export function compareVersions(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return pa[i] - pb[i];
  return 0;
}

const ms = (n) => `${n} ms`;

/**
 * One cell: the previous release's p95, this release's, and how many times
 * less the step now costs. Up to 5% either way reads as the same, since run
 * to run spread on a quiet machine is of that order for the cheapest steps,
 * and at 2 ms one 0.1 ms step of the rounding is already 5%.
 */
function cell(previous, current) {
  const ratio = previous / current;
  let change;
  if (ratio > 1.05) change = `${ratio.toFixed(1)}x faster`;
  else if (ratio < 1 / 1.05) change = `${(1 / ratio).toFixed(1)}x slower`;
  else change = 'same';
  return `${ms(previous)} to ${ms(current)} (${change})`;
}

/** The generated block: every release, newest first. */
export function renderBlock(data) {
  const lines = [START];
  const releases = [...data.releases].sort((a, b) => compareVersions(b.version, a.version));
  for (const r of releases) {
    const head = ['Renderer', 'Bars', ...BENCH_METRICS.map((m) => COLUMNS[m])];
    lines.push(
      '',
      `## ${r.version}`,
      '',
      `Measured ${r.date} against ${r.comparedWith}, both built from their release tags and run in one session on one machine: each cell is the lowest p95 of ${r.runs.release} runs of ${r.version} and ${r.runs.previous} of ${r.comparedWith}.`,
      '',
      `Machine: ${r.machine.cpu} (${r.machine.logicalCpus} logical CPUs), ${r.machine.os}, ${r.machine.browser}, ${r.machine.gl}, device pixel ratio ${r.machine.dpr}.`,
      '',
      `| ${head.join(' | ')} |`,
      `| ${head.map(() => '---').join(' | ')} |`,
    );
    for (const renderer of BENCH_RENDERERS) {
      for (const bars of BENCH_BAR_COUNTS) {
        const cells = BENCH_METRICS.map((metric) => {
          const c = r.cells.find((x) => x.renderer === renderer && x.bars === bars && x.metric === metric);
          if (!c) throw new Error(`release benchmarks: ${r.version} has no ${renderer} ${bars} ${metric} cell`);
          return cell(Math.min(...c.previousP95), Math.min(...c.releaseP95));
        });
        lines.push(`| ${renderer} | ${bars.toLocaleString('en-US')} | ${cells.join(' | ')} |`);
      }
    }
    if (r.note) lines.push('', r.note);
  }
  lines.push('', END);
  return lines.join('\n');
}

/**
 * The page with its block replaced by what the data says, and whether that
 * changed anything.
 */
export function pageWithBlock(data) {
  const page = readFileSync(PAGE_FILE, 'utf8');
  const from = page.indexOf(START);
  const to = page.indexOf(END);
  if (from < 0 || to < from) throw new Error(`release benchmarks: ${PAGE_FILE} has no generated block markers`);
  const next = page.slice(0, from) + renderBlock(data) + page.slice(to + END.length);
  return { page, next, changed: next !== page };
}

export function writePage(data) {
  const { next, changed } = pageWithBlock(data);
  if (changed) writeFileSync(PAGE_FILE, next);
  return changed;
}
