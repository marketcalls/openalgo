/**
 * docs/performance-notes.md quotes the render bench's table
 * (scripts/render-bench-budgets.mjs): every measured p95, the budget derived
 * from it, the margin and the floor. Written out by hand, those figures would
 * drift from the table the first time a budget was tightened, which is the
 * failure CLAUDE.md records for every other repeated fact in this repository.
 * So the block is generated, and this check fails when it no longer matches.
 *
 *   node scripts/check-render-bench-docs.mjs           # check, exit 1 on drift
 *   node scripts/check-render-bench-docs.mjs --write   # regenerate the block
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  BENCH_BAR_COUNTS,
  BENCH_METRICS,
  BENCH_METRIC_LABELS,
  BENCH_RENDERERS,
  RENDER_BENCH_PROFILES,
  renderBenchBudgetMs,
} from './render-bench-budgets.mjs';

const DOC = fileURLToPath(new URL('../docs/performance-notes.md', import.meta.url));
const START = '<!-- render-bench-budgets:start (generated by scripts/check-render-bench-docs.mjs --write) -->';
const END = '<!-- render-bench-budgets:end -->';

const ms = (n) => `${n} ms`;
const grouped = (n) => n.toLocaleString('en-US');

/**
 * The block as the tables say it should read: the desktop table local runs use,
 * then the runner table CI uses. Both are always rendered, so the check gives
 * the same answer on a desktop and on a runner.
 */
function renderBudgetBlock() {
  const head = ['Renderer', 'Bars', ...BENCH_METRICS.map((m) => `${BENCH_METRIC_LABELS[m]}, measured (budget)`)];
  const lines = [];
  const titles = { desktop: 'Local runs (the desktop table)', runner: 'CI (the hosted runner table)' };
  for (const name of /** @type {const} */ (['desktop', 'runner'])) {
    const profile = RENDER_BENCH_PROFILES[name];
    if (lines.length) lines.push('');
    lines.push(
      `${titles[name]}: measured on ${profile.reference}.`,
      `Budget = max(ceil(measured p95 x ${profile.margin}), ${profile.floorMs} ms).`,
      '',
      `| ${head.join(' | ')} |`,
      `| ${head.map(() => '---').join(' | ')} |`,
    );
    for (const renderer of BENCH_RENDERERS) {
      for (const bars of BENCH_BAR_COUNTS) {
        const cells = BENCH_METRICS.map((m) => {
          const measured = profile.measuredP95Ms[renderer][bars][m];
          return `${ms(measured)} (${ms(renderBenchBudgetMs(renderer, bars, m, profile))})`;
        });
        lines.push(`| ${renderer} | ${grouped(bars)} | ${cells.join(' | ')} |`);
      }
    }
  }
  return [START, ...lines, END].join('\n');
}

const doc = readFileSync(DOC, 'utf8');
const from = doc.indexOf(START);
const to = doc.indexOf(END);
if (from < 0 || to < from) {
  console.error(`check-render-bench-docs: ${DOC} has no generated budget block; add the start and end markers.`);
  process.exit(1);
}
const current = doc.slice(from, to + END.length);
const wanted = renderBudgetBlock();

if (process.argv.includes('--write')) {
  if (current !== wanted) writeFileSync(DOC, doc.slice(0, from) + wanted + doc.slice(to + END.length));
  console.log(current === wanted ? 'render bench docs: already current' : 'render bench docs: block rewritten');
} else if (current !== wanted) {
  console.error('render bench docs: docs/performance-notes.md does not quote scripts/render-bench-budgets.mjs.');
  console.error('Run: node scripts/check-render-bench-docs.mjs --write');
  process.exit(1);
} else {
  console.log('render bench docs: the budget table and the docs agree');
}
